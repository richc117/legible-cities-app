describe('.github/workflows/vuln-watch.yml', () => {
  const workflow = readFileSync(join(repo, '.github', 'workflows', 'vuln-watch.yml'), 'utf8')
  const lines = workflow.split('\n').filter((line) => !/^\s*#/.test(line))
  const body = lines.join('\n')

  it('runs weekly and by hand, and nothing else', () => {
    expect(body).toMatch(
      /\non:\n {2}schedule:\n {4}- cron: '\d+ \d+ \* \* \d'\n {2}workflow_dispatch:\n\n/,
    )
  })

  it('reads the repository and can do nothing else', () => {
    expect(body).toContain('\npermissions:\n  contents: read\n\n')
    expect(body.match(/permissions:/g)).toHaveLength(1)
    expect(body).not.toMatch(/secrets\.|id-token|GITHUB_TOKEN|issues:/)
    expect(body).toContain('persist-credentials: false')
    expect(body).toMatch(/timeout-minutes: \d+/)
  })

  it('pins every action to a full commit, as ci.yml does', () => {
    const uses = [...body.matchAll(/uses: (\S+)/g)].map((m) => m[1])
    expect(uses.length).toBeGreaterThan(0)
    for (const use of uses) expect(use).toMatch(/^[\w-]+\/[\w-]+@[0-9a-f]{40}$/)
    const ci = readFileSync(join(repo, '.github', 'workflows', 'ci.yml'), 'utf8')
    for (const line of workflow.split('\n').filter((l) => l.includes('uses: '))) {
      expect(ci).toContain(line.trim())
    }
  })

  it('runs the watch and writes its table to the job summary', () => {
    expect(body).toContain('node scripts/vuln-watch.mjs --summary "$GITHUB_STEP_SUMMARY"')
    expect(body).not.toContain('npm ci')
  })
})
