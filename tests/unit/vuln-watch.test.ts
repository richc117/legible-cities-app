describe('the judgement', () => {
  it('passes when every id is triaged and no open one is past its due date', async () => {
    const { EXIT } = await load()
    const result = await run()
    expect(result.code).toBe(EXIT.clean)
    expect(result.out).toContain('### New or untriaged: 0')
    expect(result.out).toContain('### Open within their budget: 2')
    expect(result.out).toContain('**Clean:**')
    expect(result.summary).toBe(result.out)
  })

  it('fails on an id the triage does not cover, and names it', async () => {
    const { EXIT } = await load()
    const result = await run({
      triage: triageWith((entries) => entries.filter((e) => e.id !== 'CVE-2026-76844')),
    })
    expect(result.code).toBe(EXIT.findings)
    const rows = section(result.out, 'New or untriaged')
    expect(rows).toContain('New or untriaged: 1')
    expect(rows).toContain('| CVE-2026-76844 | zlib 1.3.2 |')
    expect(rows).toContain('not in the triage')
    expect(result.out).toContain('**Failed:** 1 untriaged')
  })

  it('takes an id triaged at another version as untriaged', async () => {
    const { EXIT } = await load()
    const result = await run({
      triage: triageWith((entries) =>
        entries.map((e) => (e.id === 'CVE-2026-76844' ? { ...e, version: '1.3.1' } : e)),
      ),
    })
    expect(result.code).toBe(EXIT.findings)
    expect(section(result.out, 'New or untriaged')).toContain(
      'triaged at zlib 1.3.1, now returned for zlib 1.3.2',
    )
  })

  it('takes an id triaged for another component as untriaged', async () => {
    const { EXIT } = await load()
    const result = await run({
      triage: triageWith((entries) =>
        entries.map((e) => (e.id === 'CVE-2026-76844' ? { ...e, component: 'LOOM' } : e)),
      ),
    })
    expect(result.code).toBe(EXIT.findings)
    expect(section(result.out, 'New or untriaged')).toContain(
      'triaged for LOOM, now returned for zlib 1.3.2',
    )
  })

  it('takes an id OSV now rates otherwise as untriaged', async () => {
    const { EXIT } = await load()
    const result = await run({
      triage: triageWith((entries) =>
        entries.map((e) =>
          e.id === 'CVE-2026-107677'
            ? {
                ...e,
                osv_severity: 'CVSS:4.0/AV:N/AC:L/AT:N/PR:N/UI:N/VC:N/VI:N/VA:L/SC:N/SI:N/SA:N',
              }
            : e,
        ),
      ),
    })
    expect(result.code).toBe(EXIT.findings)
    expect(section(result.out, 'New or untriaged')).toMatch(
      /\| CVE-2026-107677 \|.*OSV now gives CVSS:4\.0\/AV:L\/AC:H/,
    )
  })

  it('fails on an open id past its due date, and not on the day it is due', async () => {
    const { EXIT } = await load()
    const due = await run({ today: '2026-11-18' })
    expect(due.code).toBe(EXIT.clean)
    expect(section(due.out, 'Open past their due date')).toContain('due date: 0')

    const late = await run({ today: '2026-11-19' })
    expect(late.code).toBe(EXIT.findings)
    const rows = section(late.out, 'Open past their due date')
    expect(rows).toContain('due date: 2')
    expect(rows).toContain('| CVE-2026-115557 | CPython 3.12.14 | critical | 2026-11-18 |')
    expect(late.out).toContain('**Failed:** 0 untriaged, 2 past their due date')
  })

  it('reports a triaged id OSV no longer returns, without failing on it', async () => {
    const { EXIT } = await load()
    const answers = new Map(
      OSV.answers.map(({ query, ids }) => [
        asked(query),
        ids.filter((id) => id !== 'CVE-2026-107677'),
      ]),
    )
    const result = await run({ fetch: standIn({ answers }).fetch })
    expect(result.code).toBe(EXIT.clean)
    const rows = section(result.out, 'Triaged, and no longer returned by OSV')
    expect(rows).toContain('returned by OSV: 1')
    expect(rows).toContain('| CVE-2026-107677 | FFmpeg 9.0.1 | not-affected |')
  })

  it("follows OSV's pages, and asks again only for the query that has another", async () => {
    const { EXIT } = await load()
    const zlib = 'GIT https://github.com/madler/zlib @ v1.3.2'
    const answers = new Map(
      OSV.answers.map(({ query, ids }) => [asked(query), asked(query) === zlib ? [] : ids]),
    )
    const stand = standIn({ answers, paged: new Map([[zlib, ['CVE-2026-76844']]]) })
    const result = await run({ fetch: stand.fetch })
    expect(result.code).toBe(EXIT.clean)
    const batches = stand.calls.filter((c) => c.queries !== undefined)
    expect(batches).toHaveLength(2)
    expect(batches[1].queries).toEqual([
      {
        package: { ecosystem: 'GIT', name: 'https://github.com/madler/zlib' },
        version: 'v1.3.2',
        page_token: 'page-2',
      },
    ])
    expect(section(result.out, 'New or untriaged')).toContain('untriaged: 0')
  })
})

describe('a failure to reach OSV', () => {
  const cases: [string, () => Promise<Response>, RegExp][] = [
    ['the network refusing', () => Promise.reject(new TypeError('fetch failed')), /fetch failed/],
    [
      'an HTTP error',
      () => Promise.resolve(json({ code: 14, message: 'unavailable' }, 503)),
      /querybatch: HTTP 503/,
    ],
    [
      'an answer that is not JSON',
      () => Promise.resolve(new Response('<html>busy</html>', { status: 200 })),
      /querybatch: the answer is not JSON/,
    ],
    [
      'fewer results than queries',
      () => Promise.resolve(json({ results: [{}] })),
      /querybatch answered 1 results for 11 queries/,
    ],
  ]

  it.each(cases)('never calls a network failure clean: %s', async (_, fetch, said) => {
    const { EXIT } = await load()
    const result = await run({ fetch: () => fetch() })
    expect(result.code).toBe(EXIT.unreachable)
    expect(result.err).toMatch(said)
    expect(result.err).toContain('Nothing was judged')
    expect(result.out).not.toContain('Clean')
    expect(result.summary).toContain('**OSV could not be asked:**')
    expect(result.summary).not.toContain('Clean')
  })

  it('never calls a network failure clean: a record that will not come', async () => {
    const { EXIT } = await load()
    const stand = standIn()
    const result = await run({
      fetch: (url, init) =>
        url.includes('/v1/vulns/') ? Promise.resolve(json({}, 500)) : stand.fetch(url, init),
    })
    expect(result.code).toBe(EXIT.unreachable)
    expect(result.err).toMatch(/vulns\/[A-Z]+-[0-9-]+: HTTP 500/)
    expect(result.out).toBe('')
  })
})

describe('the triage', () => {
  const entry = (change: Partial<Entry> & Record<string, unknown> = {}): Entry => ({
    id: 'CVE-2026-0001',
    component: 'zlib',
    version: '1.3.2',
    severity: 'high',
    osv_severity: 'CVSS:4.0/AV:N/AC:H/AT:N/PR:N/UI:N/VC:N/VI:H/VA:H/SC:N/SI:N/SA:N',
    verdict: 'open',
    reason: 'Reached through the feed download. Fixed in the next release.',
    triaged: '2026-11-04',
    due: '2026-11-18',
    ...change,
  })
  const problems = async (...entries: Entry[]): Promise<string[]> =>
    (await load()).validateTriage({ entries })

  it('takes a well-formed entry of every verdict', async () => {
    const { VERDICTS } = await load()
    for (const verdict of VERDICTS) {
      const one = entry({ verdict })
      if (verdict !== 'open') delete one.due
      expect(await problems(one), verdict).toEqual([])
    }
  })

  it('refuses an open entry with no due date, and a closed one with one', async () => {
    const open = entry()
    delete open.due
    expect(await problems(open)).toEqual(['CVE-2026-0001: is open and has no "due" date'])
    expect(await problems(entry({ verdict: 'not-reachable' }))).toEqual([
      'CVE-2026-0001: has a "due" date although it is not-reachable, not open',
    ])
  })

  it('refuses a due date past the budget for its severity', async () => {
    const { BUDGET_DAYS, addDays } = await load()
    expect(BUDGET_DAYS).toEqual({ critical: 14, high: 14, medium: 60, low: 60, unrated: 60 })
    expect(await problems(entry({ due: addDays('2026-11-04', 14) }))).toEqual([])
    expect(await problems(entry({ due: addDays('2026-11-04', 15) }))).toEqual([
      'CVE-2026-0001: is due 2026-11-19, past the 14-day budget for high (2026-11-18)',
    ])
    expect(await problems(entry({ severity: 'medium', due: addDays('2026-11-04', 60) }))).toEqual(
      [],
    )
    expect(await problems(entry({ due: '2026-11-03' }))).toEqual([
      'CVE-2026-0001: is due before it was triaged',
    ])
  })

  it('refuses a verdict or a severity outside the set, and a rating OSV does not give', async () => {
    expect(await problems(entry({ verdict: 'wontfix' }))).toContain(
      'CVE-2026-0001: has verdict "wontfix", not one of not-affected, not-reachable, fixed-in-pin, open',
    )
    expect(await problems(entry({ severity: 'moderate' }))).toContain(
      'CVE-2026-0001: has severity "moderate", not one of critical, high, medium, low, unrated',
    )
    expect(await problems(entry({ osv_severity: null }))).toEqual([
      'CVE-2026-0001: is rated although OSV gives it no severity: "unrated"',
    ])
    expect(await problems(entry({ severity: 'unrated' }))).toEqual([
      'CVE-2026-0001: is "unrated" although OSV gives it a severity: rate it from that',
    ])
  })

  it('refuses a missing or unknown field, a repeated id, a bad date and a long reason', async () => {
    const bare = entry() as Partial<Entry>
    delete bare.reason
    expect(await problems(bare as Entry)).toEqual(['CVE-2026-0001: has no "reason"'])
    expect(await problems(entry({ note: 'x' }))).toEqual([
      'CVE-2026-0001: has a field "note" the form lacks',
    ])
    expect(await problems(entry(), entry())).toEqual(['CVE-2026-0001: is triaged twice'])
    expect(await problems(entry({ triaged: '4 Nov 2026' }))).toContain(
      'CVE-2026-0001: has a "triaged" that is not a YYYY-MM-DD date',
    )
    expect(await problems(entry({ reason: 'One. Two. Three. Four.' }))).toEqual([
      'CVE-2026-0001: has a reason of 4 sentences, where one to three are asked',
    ])
    expect((await load()).validateTriage([])).toEqual([
      'the triage is not an object with an "entries" list',
    ])
  })

  it('counts a version number or an abbreviation as part of a sentence', async () => {
    const { sentences } = await load()
    expect(sentences('Fixed in CPython 3.12.16, in the 20261026 release.')).toBe(1)
    expect(sentences('The build has no TLS (ADR-040). The proof refuses it.')).toBe(2)
  })
})

